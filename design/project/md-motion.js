export function injectIcons() {
  document.querySelectorAll('[data-icon]').forEach((n) => {
    if (!n.__icon) {
      n.innerHTML = ICONS[n.getAttribute('data-icon')] || '';
      n.__icon = 1;
    }
  });
}

function reveal(t) {
  const d = +(t.getAttribute('data-delay') || 0);
  setTimeout(() => {
    t.style.opacity = '1';
    t.style.transform = 'none';
    t.style.clipPath = 'inset(0 0 0 0)';
  }, d);
}

function countUp(node) {
  const to = parseFloat(node.getAttribute('data-to'));
  const dec = +(node.getAttribute('data-decimals') || 0);
  const suf = node.getAttribute('data-suffix') || '';
  const pre = node.getAttribute('data-prefix') || '';
  const dur = 1600,
    start = performance.now();
  const tick = (now) => {
    let p = Math.min((now - start) / dur, 1);
    p = 1 - Math.pow(1 - p, 3);
    node.textContent = pre + (to * p).toFixed(dec) + suf;
    if (p < 1) requestAnimationFrame(tick);
  };
  requestAnimationFrame(tick);
}

// Split a plain-text element into word spans that rise into place (editorial line reveal)
function splitWords(el) {
  if (el.__split) return;
  el.__split = 1;
  const text = el.textContent;
  el.textContent = '';
  el.style.opacity = '1';
  const words = text.split(/(\s+)/);
  el.__words = [];
  words.forEach((w) => {
    if (/^\s+$/.test(w)) {
      el.appendChild(document.createTextNode(w));
      return;
    }
    const outer = document.createElement('span');
    outer.style.cssText =
      'display:inline-block;overflow:hidden;vertical-align:top;padding-bottom:.06em;margin-bottom:-.06em';
    const inner = document.createElement('span');
    inner.style.cssText =
      'display:inline-block;transform:translateY(112%);transition:transform .8s cubic-bezier(.19,1,.22,1)';
    inner.textContent = w;
    outer.appendChild(inner);
    el.appendChild(outer);
    el.__words.push(inner);
  });
}
function playWords(el) {
  if (!el.__words) return;
  el.__words.forEach((w, i) => {
    setTimeout(() => {
      w.style.transform = 'translateY(0)';
    }, i * 55);
  });
}

function scramble(el) {
  if (el.__scr) return;
  el.__scr = 1;
  const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ!@#$%&*<>/';
  const target = el.textContent;
  const dur = Math.min(1400, 380 + target.length * 36);
  const start = performance.now();
  el.style.opacity = '1';
  const rnd = () => chars[Math.floor(Math.random() * chars.length)];
  const tick = (now) => {
    const p = Math.min((now - start) / dur, 1);
    const reveal = Math.floor(p * target.length);
    let out = '';
    for (let i = 0; i < target.length; i++) {
      const ch = target[i];
      if (i < reveal || ch === ' ' || ch === '\n') out += ch;
      else out += rnd();
    }
    el.textContent = out;
    if (p < 1) requestAnimationFrame(tick);
    else el.textContent = target;
  };
  requestAnimationFrame(tick);
}

