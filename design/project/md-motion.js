function magnetic(el) {
  if (el.__mag) return;
  el.__mag = 1;
  const strength = +(el.getAttribute('data-magnetic') || 0.35);
  el.style.transition = 'transform .25s cubic-bezier(.2,.7,.2,1)';
  el.addEventListener('mousemove', (e) => {
    const r = el.getBoundingClientRect();
    const x = e.clientX - (r.left + r.width / 2);
    const y = e.clientY - (r.top + r.height / 2);
    el.style.transform = `translate(${x * strength}px,${y * strength}px)`;
  });
  el.addEventListener('mouseleave', () => {
    el.style.transform = 'translate(0,0)';
  });
}

function tilt(el) {
  if (el.__tilt) return;
  el.__tilt = 1;
  const max = +(el.getAttribute('data-tilt') || 6);
  el.style.transition = 'transform .3s cubic-bezier(.2,.7,.2,1)';
  el.style.transformStyle = 'preserve-3d';
  el.addEventListener('mousemove', (e) => {
    const r = el.getBoundingClientRect();
    const px = (e.clientX - r.left) / r.width - 0.5;
    const py = (e.clientY - r.top) / r.height - 0.5;
    el.style.transform = `perspective(900px) rotateY(${px * max}deg) rotateX(${-py * max}deg)`;
  });
  el.addEventListener('mouseleave', () => {
    el.style.transform = 'perspective(900px) rotateY(0) rotateX(0)';
  });
}

function scrollProgress() {
  let bar = document.getElementById('md-scrollbar');
  if (!bar) {
    bar = document.createElement('div');
    bar.id = 'md-scrollbar';
    bar.style.cssText =
      'position:fixed;top:0;left:0;height:2px;width:0;z-index:200;background:linear-gradient(90deg,#4f46e5,#ff441f);transition:width .1s linear;pointer-events:none';
    document.body.appendChild(bar);
  }
  const upd = () => {
    const h = document.documentElement.scrollHeight - window.innerHeight;
    bar.style.width = (h > 0 ? (window.scrollY / h) * 100 : 0) + '%';
  };
  window.addEventListener('scroll', upd, { passive: true });
  upd();
}

function customCursor() {
  if (window.matchMedia('(pointer:coarse)').matches) return;
  if (document.getElementById('md-cursor')) return;
  const dot = document.createElement('div');
  dot.id = 'md-cursor';
  dot.style.cssText =
    'position:fixed;top:0;left:0;width:10px;height:10px;background:#4f46e5;border-radius:50%;pointer-events:none;z-index:9999;transform:translate(-50%,-50%);transition:width .2s,height .2s,background .2s;will-change:transform;opacity:0';
  document.body.appendChild(dot);
  let x = innerWidth / 2,
    y = innerHeight / 2,
    tx = x,
    ty = y;
  window.addEventListener('mousemove', (e) => {
    tx = e.clientX;
    ty = e.clientY;
    dot.style.opacity = '1';
  });
  const loop = () => {
    x += (tx - x) * 0.35;
    y += (ty - y) * 0.35;
    dot.style.left = x + 'px';
    dot.style.top = y + 'px';
    requestAnimationFrame(loop);
  };
  loop();
  const grow = () => {
    dot.style.width = '16px';
    dot.style.height = '16px';
    dot.style.background = '#ff441f';
  };
  const shrink = () => {
    dot.style.width = '10px';
    dot.style.height = '10px';
    dot.style.background = '#4f46e5';
  };
  document.addEventListener('mouseover', (e) => {
    if (e.target.closest('a,button,[data-magnetic],summary,input,select,textarea')) grow();
    else shrink();
  });
}

export function initMotion(opts) {
  opts = opts || {};
  injectIcons();
  injectCardStyles();
  const io =
    'IntersectionObserver' in window
      ? new IntersectionObserver(
          (entries) => {
            entries.forEach((e) => {
              if (e.isIntersecting) {
                reveal(e.target);
                io.unobserve(e.target);
              }
            });
          },
          { threshold: 0.12, rootMargin: '0px 0px -8% 0px' },
        )
      : null;
  document.querySelectorAll('[data-reveal]').forEach((n) => {
    if (n.__rev) return;
    n.__rev = 1;
    if (io) io.observe(n);
    else reveal(n);
  });

  // split-word headline reveals
  document.querySelectorAll('[data-split]').forEach((n) => splitWords(n));
  const sio =
    'IntersectionObserver' in window
      ? new IntersectionObserver(
          (entries) => {
            entries.forEach((e) => {
              if (e.isIntersecting) {
                playWords(e.target);
                sio.unobserve(e.target);
              }
            });
          },
          { threshold: 0.2 },
        )
      : null;
  document.querySelectorAll('[data-split]').forEach((n) => {
    if (n.__sobs) return;
    n.__sobs = 1;
    if (sio) sio.observe(n);
    else playWords(n);
  });

  const cio =
    'IntersectionObserver' in window
      ? new IntersectionObserver(
          (entries) => {
            entries.forEach((e) => {
              if (e.isIntersecting) {
                countUp(e.target);
                cio.unobserve(e.target);
              }
            });
          },
          { threshold: 0.5 },
        )
      : null;
  document.querySelectorAll('[data-count]').forEach((n) => {
    if (n.__cnt) return;
    n.__cnt = 1;
    if (cio) cio.observe(n);
    else countUp(n);
  });

  document.querySelectorAll('[data-magnetic]').forEach(magnetic);
  document.querySelectorAll('[data-tilt]').forEach(tilt);
  const scrio =
    'IntersectionObserver' in window
      ? new IntersectionObserver(
          (entries) => {
            entries.forEach((e) => {
              if (e.isIntersecting) {
                scramble(e.target);
                scrio.unobserve(e.target);
              }
            });
          },
          { threshold: 0.3 },
        )
      : null;
  document.querySelectorAll('[data-scramble]').forEach((n) => {
    if (n.__sobs2) return;
    n.__sobs2 = 1;
    if (scrio) scrio.observe(n);
    else scramble(n);
  });
  if (opts.progress !== false) scrollProgress();
  if (opts.cursor) customCursor();
}
